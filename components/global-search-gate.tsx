// Александр, 18.09.2026: «поиск с фильтрами наверное надо показывать не
// только на главной для удобства... мб пусть живет почти везде и просто
// редиректит потом».
//
// Строка поиска в шапке рисуется формой фильтров (components/
// filters-form.tsx), которая телепортирует себя в #nav-search-slot. До
// сих пор эту форму подключали только две страницы -- лента и таланты,
// -- и на всех остальных место в шапке оставалось пустым.
//
// Теперь форма подключена ещё и в общем макете (app/layout.tsx), а этот
// маленький сторож нужен ровно для одного: на самих ленте и талантах
// НЕ рисовать вторую такую же. Две формы телепортировались бы в одно и
// то же место в шапке и наложились друг на друга.
//
// Почему сторож отдельный и клиентский: путь страницы на сервере в
// макете неизвестен, узнать его можно только в браузере (usePathname).
// Форму он получает готовой, через children, -- она остаётся серверной
// и данные для фильтров тянет по-прежнему на сервере.
"use client";

import { usePathname } from "next/navigation";

/** Страницы, которые подключают форму фильтров сами. */
const OWN_SEARCH = new Set(["/", "/talents"]);

export function GlobalSearchGate({ children }: { children: React.ReactNode }) {
  const pathname = usePathname();
  if (OWN_SEARCH.has(pathname)) return null;
  return <>{children}</>;
}
