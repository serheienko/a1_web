// ("use client"), а клиентский компонент не умеет экспортировать
// metadata. Поэтому отдельный серверный layout: он ничего не рисует,
// только проставляет заголовок и noindex на весь раздел.
//
// Зачем noindex. До этой правки семь адресов (/sign-in, /chats,
// /chats/<id>, /contacts, /my-activity, /onboarding/verify,
// /onboarding/profile) отдавали роботу ОДИН И ТОТ ЖЕ заголовок "A1 Web",
// одно и то же описание из корневого layout и пустой каркас без единой
// строки контента -- вся страница собирается в браузере после входа.
// Для поиска это семь одинаковых пустых дублей на домене, которому и так
// нечем хвастаться. Ни одна из них не имеет смысла в выдаче: попасть
// туда можно только залогинившись.
//
// follow: false тоже намеренно -- дальше по этим страницам ходить некуда,
// всё содержимое появляется только у вошедшего пользователя.

