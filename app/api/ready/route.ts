import { warmSegmentIndex } from "@/lib/a1/segment-index";

export const dynamic = "force-dynamic";

let ready = false;

export async function GET() {
  if (!ready) {
    const port = process.env.PORT || "3000";
    try {
      const r = await fetch(`http://127.0.0.1:${port}/game-map/data?region=ua`, { cache: "no-store" });
      await r.arrayBuffer();
    } catch {
      // бекенд недоступний -- не тримаємо деплой: карта збереться пізніше
    }
    // 10.10.2026. Карта гріє спільний список вакансій, але НЕ покажчик
    // сегментів -- його збирає перший, хто відкриє посадочну сторінку, і
    // платить за це 23-28 секунд білого екрана. Гріємо тут же: обхід бази
    // вже зроблено вище, лишається розкласти вакансії по сегментах.
    try {
      await warmSegmentIndex();
    } catch {
      // те саме: не тримаємо деплой, покажчик збереться на першому запиті
    }
    ready = true;
  }
  return Response.json({ ok: true }, { headers: { "Cache-Control": "no-store" } });
}
