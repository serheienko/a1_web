// «Забрати профіль» не меняются при переключении языка — только после
// перезагрузки. Должно меняться сразу, как верхние табы Jobs/Talents).
//
// Почему табы меняются, а этот блок нет. Статичный текст сайта идёт
// через <T> (components/t.tsx): сервер печатает все девять переводов
// сразу, а CSS-класс lang-XX на <html> решает, какой из них видно.
// Переключатель языка меняет этот класс — и текст меняется мгновенно,
// без всякого JS.
//
// Но у диалогов, меню и форм строки собираются в самом JS
// (STRINGS[lang]), потому что их надо подставлять в aria-label, title,
// тексты ошибок — туда <T> не вставишь. Там язык брал вот такой хук, и
// в каждом из 31 файла лежала его дословная копия, читавшая класс
// ОДИН раз при монтировании:
//
//     useEffect(() => { ...прочитать класс... }, []);
//
// Пустой список зависимостей — это и есть баг: после переключения
// языка компонент уже смонтирован, эффект больше не запустится, и
// строка остаётся на прежнем языке до перезагрузки страницы.
//
// Здесь тот же хук, но он ещё и подписывается на изменение атрибута
// class у <html> (MutationObserver) — ровно то место, куда пишет
// components/settings-menu.tsx. Переключили язык — все такие тексты
// меняются в тот же кадр, вместе с <T>.
//
// Одна копия на весь проект: расхождение между 31 копией — это как раз
// то, из-за чего фикс пришлось бы делать 31 раз.
"use client";

import { useEffect, useState } from "react";
import { LOCALES, LOCALE_CLASS, type Locale } from "@/components/t";

export function useActiveLocale(): Locale {
  // "uk" до первой отрисовки на клиенте — как и раньше. Сервер языка
  // не знает (класс ставит скрипт в app/layout.tsx уже в браузере),
  // поэтому любое другое значение по умолчанию давало бы мигание.
  const [lang, setLang] = useState<Locale>("uk");

  useEffect(() => {
    const root = document.documentElement;

    const read = () => {
      const active = LOCALES.find((l) => root.classList.contains(LOCALE_CLASS[l]));
      if (!active) return;
      // Сравнение с предыдущим значением: MutationObserver срабатывает
      // и на переключение темы (dark/light живут в том же атрибуте), а
      // лишний setState перерисовывал бы половину страницы впустую.
      setLang((prev) => (prev === active ? prev : active));
    };

    read();
    const observer = new MutationObserver(read);
    observer.observe(root, { attributes: true, attributeFilter: ["class"] });
    return () => observer.disconnect();
  }, []);

  return lang;
}
