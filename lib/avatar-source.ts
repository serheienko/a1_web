// Ширина одна на весь сайт, и это принципиально: кеш картинок
// ключуется по id документа, поэтому разные ширины по местам означали
// бы несколько копий одного и того же человека, и каждая качалась бы
// заново. 256 -- с запасом: самый крупный аватар в интерфейсе 120
// пикселей, на экране двойной плотности это 240.
const AVATAR_WIDTH_PX = 256;

function toDownloadUrl(proxyUrl: string): string {
  return proxyUrl.replace(/^(\/api\/media\/[^/?]+)(\?|$)/, "$1/download$2");
}

/** Адрес уменьшенной копии аватарки. Для чужих адресов (дефолтные коты
 *  лежат прямо в бакете, а не за нашим /api/media) возвращает исходный
 *  адрес без изменений. */
export function avatarSourceUrl(proxyUrl: string): string {
  const download = toDownloadUrl(proxyUrl);
  if (!download.startsWith("/api/media/")) return proxyUrl;
  return download + (download.includes("?") ? "&" : "?") + `w=${AVATAR_WIDTH_PX}`;
}
