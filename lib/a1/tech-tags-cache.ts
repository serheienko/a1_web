// ЧТО ПРОИСХОДИЛО. extractTechTags прогоняет словарь из восьмидесяти
// технологий по ВСЕМУ тексту вакансии. Вакансий тридцать пять тысяч, то
// есть один полный разбор -- это десятки секунд работы процессора. А
// делался он:
//   * в указателе сегментов (lib/a1/segment-index.ts) -- заново каждый раз,
//     когда «догон» свежих вакансий подменял список, то есть раз в полчаса;
//   * в указателе стеков (lib/a1/tech-index.ts) -- заново раз в час;
//   * и внутри каждого из них по нескольку раз на одну и ту же вакансию.
// Кто в этот момент первым открывал посадочную страницу, ждал 23-28 секунд.
//
// ЧТО ТЕПЕРЬ. Результат разбора лежит здесь, ключ -- номер вакансии. Текст
// вакансии не меняется, поэтому разобранная один раз вакансия больше не
// разбирается никогда. После «догона» пересчёт стоит столько, сколько в нём
// новых вакансий, -- полсотни вместо тридцати пяти тысяч.
//
// Память: тридцать пять тысяч коротких списков -- несколько мегабайт. Чтобы
// кэш не рос бесконечно на снятых вакансиях, prune оставляет только те, что
// есть в текущем списке.

import type { WebPost } from "@/types/web-post";
import { extractTechTags } from "@/lib/seo/job-tech-tags";

let memo = new Map<string, string[]>();

/** Технологии вакансии. Разбор текста -- один раз за всё время жизни процесса. */
export function techsOfPost(post: WebPost): string[] {
  let techs = memo.get(post.id);
  if (!techs) {
    techs = [...new Set(extractTechTags(post.title, post.contentText))];
    memo.set(post.id, techs);
  }
  return techs;
}

/** Выбросить разбор вакансий, которых в списке больше нет. Зовётся при
 *  пересборке указателей, когда кэш заметно перерос живой список. */
export function pruneTechCache(posts: WebPost[]): void {
  if (memo.size <= posts.length * 1.5) return;
  const next = new Map<string, string[]>();
  for (const post of posts) {
    const techs = memo.get(post.id);
    if (techs) next.set(post.id, techs);
  }
  memo = next;
}
