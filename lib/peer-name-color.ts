// lib/peer-name-color.ts
//
// Цвета имён в обсуждении. 2026-09-16, по референсу Александра из
// Telegram: в групповой переписке имя автора над сообщением и имя в
// цитате окрашены, причём у разных людей цвета разные, иначе две
// соседние цитаты читаются как одна.
//
// Александр: «нам надо прям какую-то придумать модельку, чтобы там у
// 10, не знаю, или 15 пользователей были разные цвета имён и вот так
// оно, типа, не дублировалось».
//
// Модель ровно та же, что у Telegram, плюс одна честная добавка:
//
//   1. У каждого человека есть СВОЙ цвет: номер считается из его id
//      (хэш), поэтому один и тот же человек всегда одного цвета -- на
//      любой вакансии, в любой сессии, и на сервере, и в браузере.
//      Никакого состояния хранить не надо.
//   2. Хэш, естественно, иногда даёт двоим один и тот же номер. В
//      пределах ОДНОГО обсуждения это видно сразу, поэтому цвета
//      раздаются по списку: если желаемый номер уже занят кем-то выше,
//      берётся ближайший свободный. Пока авторов не больше, чем цветов
//      в палитре, повторов не будет вовсе.
//
// Больше восьми авторов в одной ветке -- цвета начнут повторяться, и
// это не лечится: палитра конечна. Восемь -- это не «сколько влезло»,
// а сколько РАЗЛИЧИМЫХ цветов имени читаются на белом и на чёрном фоне
// одновременно; девятый был бы уже почти таким же, как один из восьми,
// и толку от него было бы столько же, сколько от повтора.
//
// Сами цвета живут в app/globals.css как --peer-name-0..7, парами
// светлая/тёмная тема -- здесь только номер.

export const PEER_NAME_COLOR_COUNT = 8;

/** Номер цвета «по умолчанию» -- из id. Одинаковый на сервере и в браузере. */
export function peerNameColorIndex(seed: string): number {
  // FNV-1a, 32 бита. Нужен не криптостойкий хэш, а просто ровное
  // размазывание коротких строк по восьми корзинам.
  let h = 0x811c9dc5;
  for (let i = 0; i < seed.length; i += 1) {
    h ^= seed.charCodeAt(i);
    h = Math.imul(h, 0x01000193);
  }
  return (h >>> 0) % PEER_NAME_COLOR_COUNT;
}

/** CSS-значение цвета по номеру. */
export function peerNameColorVar(index: number): string {
  return `var(--peer-name-${index % PEER_NAME_COLOR_COUNT})`;
}

/**
 * Раздать цвета участникам обсуждения без повторов, пока их не больше
 * восьми. Порядок важен: seeds идут в том же порядке, что и
 * комментарии, поэтому цвет человека не «прыгает» при добавлении
 * нового комментария в конец.
 */
export function assignPeerNameColors(seeds: Array<string | null | undefined>): Map<string, string> {
  const taken = new Set<number>();
  const result = new Map<string, string>();
  for (const raw of seeds) {
    const seed = raw ?? "";
    if (!seed || result.has(seed)) continue;
    let index = peerNameColorIndex(seed);
    // Желаемый занят -- идём по кругу до первого свободного. Круг
    // замкнётся только когда заняты все восемь, тогда берём желаемый.
    for (let step = 0; step < PEER_NAME_COLOR_COUNT && taken.has(index); step += 1) {
      index = (index + 1) % PEER_NAME_COLOR_COUNT;
    }
    taken.add(index);
    result.set(seed, peerNameColorVar(index));
  }
  return result;
}
